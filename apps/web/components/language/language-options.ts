export function findLanguage(
  locale: string,
): LanguageOption | undefined {
  return languageOptions.find(
    (language) =>
      language.locale
      .toLowerCase()
      === locale.toLowerCase(),
  );
}


export function getLanguageName(
  locale: string,
): string {
  const language =
    findLanguage(locale);

  if (language) {
    return language.name;
  }

  try {
    const displayNames =
      new Intl.DisplayNames(
        ["en"],
        {
          type: "language",
        },
      );

    return (
      displayNames.of(locale)
      ?? locale
    );
  } catch {
    return locale;
  }
}


export function getDirection(
  locale: string,
): "ltr" | "rtl" {
  const language =
    findLanguage(locale);

  if (language) {
    return language.direction;
  }

  const languageCode =
    locale
      .split("-")[0]
      .toLowerCase();

  const rtlLanguages =
    new Set([
      "ar",
      "fa",
      "he",
      "ps",
      "ur",
      "dv",
      "ku",
      "yi",
    ]);

  return rtlLanguages.has(
    languageCode,
  )
    ? "rtl"
    : "ltr";
}
